export function bookingText<T>(text: T, locale: BookingLocale = 'zh', values: readonly unknown[] = []): T extends string ? string : T {
  if (typeof text !== 'string') return text as T extends string ? string : T;
  const exact = BOOKING_ENGLISH_COPY[text];
  const trimmed = BOOKING_ENGLISH_COPY[text.trim()];
  const template = locale === 'en'
    ? exact ?? (trimmed === undefined ? text : `${text.match(/^\s*/)?.[0] ?? ''}${trimmed}${text.match(/\s*$/)?.[0] ?? ''}`)
    : text;
  return template.replace(/\{(\d+)\}/g, (match, index: string) =>
    Number(index) < values.length ? String(values[Number(index)] ?? '') : match,
  ) as T extends string ? string : T;
}

/** Use only for known system feedback, never patient names, clinical notes or form values. */
export function bookingFeedback(text: string, locale: BookingLocale = 'zh'): string {
  if (locale === 'zh') return text;
  const translated = bookingText(text, locale);
  if (translated !== text || !/[\u3400-\u9fff]/.test(text)) return translated;
  const masked = text.match(/^登入連結已發送到 (.+) 的 WhatsApp。$/);
  if (masked) return `A sign-in link has been sent to ${masked[1]} on WhatsApp.`;
  return bookingText('暫時未能完成操作，請稍後再試或聯絡診所。', locale);
}
